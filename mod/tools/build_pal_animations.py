"""
PAL Animation Authoring & Verification Script for Milestone 1.
Generates genuine Bedrock PAL .animation.json files for all missing, replaced, canonical weapon,
and upgraded player animations adhering to:
1. Strict 6-bone rig: body, head, right_arm, left_arm, right_leg, left_leg (NEVER torso).
2. Zero-Snap Contract: rotation/position at 0.0s matches animation_length exactly.
3. Authentic martial arts choreography (Hung Gar, Baguazhang, Tai Chi, Northern Shaolin, Weapon forms).
4. Timeline duration synchronization with SkillTimeline.
5. Dual key registration in 'animations': "animation.avatar_elements.<name>" and "<name>".
"""

import json
from pathlib import Path

ANIM_DIR = Path("src/client/resources/assets/avatar_elements/player_animations")
ANIM_DIR.mkdir(parents=True, exist_ok=True)

BONES = ["body", "head", "right_arm", "left_arm", "right_leg", "left_leg"]

def build_clip(duration, loop, bones_data):
    # Ensure all 6 bones exist
    for b in BONES:
        if b not in bones_data:
            raise ValueError(f"Missing bone {b}")
    # Verify zero-snap contract
    dur_str = f"{duration:.2f}"
    dur_alt = f"{duration:g}"
    for b_name, b_val in bones_data.items():
        for ch in ["rotation", "position"]:
            if ch in b_val:
                kfs = b_val[ch]
                if "0.0" not in kfs:
                    raise ValueError(f"Bone {b_name} {ch} missing keyframe 0.0")
                # find end key
                end_val = None
                if dur_str in kfs:
                    end_val = kfs[dur_str]
                elif dur_alt in kfs:
                    end_val = kfs[dur_alt]
                else:
                    raise ValueError(f"Bone {b_name} {ch} missing end keyframe for {duration}")
                
                start_val = kfs["0.0"]
                if start_val != end_val:
                    raise ValueError(f"Zero-snap violation on {b_name} {ch}: start {start_val} != end {end_val}")

                # Ensure both dur_str and dur_alt are present if they differ
                if dur_str != dur_alt:
                    kfs[dur_str] = end_val
                    kfs[dur_alt] = end_val

    return {
        "loop": loop,
        "animation_length": duration,
        "bones": bones_data
    }

def save_animation(name, duration, loop, bones_data):
    clip = build_clip(duration, loop, bones_data)
    doc = {
        "format_version": "1.8.0",
        "animations": {
            f"animation.avatar_elements.{name}": clip,
            name: clip
        }
    }
    out_file = ANIM_DIR / f"{name}.animation.json"
    out_file.write_text(json.dumps(doc, indent=2), encoding="utf-8")
    print(f"[OK] Wrote {out_file.name} (length={duration}s, 6 bones, dual-keyed, zero-snap verified)")

print("Generating PAL .animation.json files...")

